// Builds src/styles/qi-tokens.css from design-tokens/qi-tokens.json.
// Pure functions so the token pipeline is unit-tested (src/styles/qi-tokens.test.ts).

const RADIUS_TOKENS = {
  none: 'border-radius-none',
  sm: 'border-radius-sm',
  md: 'border-radius-md',
  lg: 'border-radius-lg',
  full: 'border-radius-round',
  button: 'button-radius',
  card: 'card-radius',
  checkbox: 'checkbox-radius',
  chip: 'chip-radius',
  overlay: 'overlay-radius',
  form: 'form-elements-radius',
  tag: 'tag-radius',
  message: 'page-level-message-radius',
  snackbar: 'snackbar-radius',
};

function declarations(entries, indent) {
  return Object.entries(entries)
    .map(([name, value]) => `${indent}--qi-${name}: ${value};`)
    .join('\n');
}

/** Returns the full CSS text for the given token document. */
export function buildQiCss(tokens) {
  const missingDark = Object.keys(tokens.light).filter((key) => !(key in tokens.dark));
  if (missingDark.length > 0) {
    throw new Error(`Tokens without a dark value: ${missingDark.join(', ')}`);
  }
  for (const [alias, token] of Object.entries(RADIUS_TOKENS)) {
    if (!(token in tokens.shape)) throw new Error(`Missing shape token ${token} (radius-${alias})`);
  }

  const colours = Object.keys(tokens.light)
    .map((name) => `  --color-${name}: var(--qi-${name});`)
    .join('\n');
  const radii = Object.entries(RADIUS_TOKENS)
    .map(([alias, token]) => `  --radius-${alias}: var(--qi-${token});`)
    .join('\n');

  return `/* GENERATED by scripts/generate-qi-tokens.mjs from design-tokens/qi-tokens.json. Do not edit. */
/* Source: ${tokens.source} (extracted ${tokens.extracted}) */

:root {
  color-scheme: light;
${declarations(tokens.shape, '  ')}
${declarations(tokens.light, '  ')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${declarations(tokens.dark, '    ')}
  }
}

:root[data-theme='dark'] {
  color-scheme: dark;
${declarations(tokens.dark, '  ')}
}

/* Only Qi colours exist as Tailwind utilities: bg-surface-default, text-text-subdued, ... */
@theme inline {
  --color-*: initial;
${colours}
  --radius-*: initial;
${radii}
}
`;
}
