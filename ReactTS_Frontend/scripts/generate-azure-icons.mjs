#!/usr/bin/env node
// Usage: npm run azure-icons -- <folder> — the "Icons" folder of Microsoft's Azure_Public_Service_Icons zip
// (learn.microsoft.com/azure/architecture/icons), unzipped. Writes the icons the web app serves, its index, the
// API's copy (it draws them in SAD PDFs) and the ids and names the API knows. Microsoft's terms: public/azure-icons/NOTICE.md.
import { copyFileSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { buildIconIndex } from './azure-icons.mjs';

const source = process.argv[2];
if (!source) {
  console.error('Usage: npm run azure-icons -- <unzipped Icons folder>');
  process.exit(1);
}
const files = readdirSync(source, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .flatMap((folder) => readdirSync(join(source, folder.name)).filter((file) => file.endsWith('.svg')).map((file) => ({ category: folder.name, file })));
const index = buildIconIndex(files);
const where = new Map(files.map(({ category, file }) => [file, join(source, category, file)]));

const NOTICE = `# Azure architecture icons

From Microsoft's official set (Azure_Public_Service_Icons, learn.microsoft.com/azure/architecture/icons), copied by
ReactTS_Frontend/scripts/generate-azure-icons.mjs. Product owner approval: 2026-10-22 licence exception, 2026-10-23 and 2026-10-24 downloads.

Microsoft permits the use of these icons in architectural diagrams, training materials or documentation, and allows
copying, distributing and displaying them only for that use. They are not open source. Do not crop, flip, rotate,
distort or recolour them; show the product name near the icon.
`;
// The web app serves them; the API draws them in SAD PDFs (its own copy, deployed with it).
for (const target of [new URL('../public/azure-icons/', import.meta.url), new URL('../../NestJS_Backend/src/modules/sad/azure-icons/', import.meta.url)]) {
  rmSync(target, { recursive: true, force: true });
  mkdirSync(target, { recursive: true });
  for (const icon of index) copyFileSync(where.get(icon.file), new URL(`${icon.id}.svg`, target));
  writeFileSync(new URL('NOTICE.md', target), NOTICE);
}

const header = '// GENERATED by scripts/generate-azure-icons.mjs from Microsoft\'s Azure icon set (terms: ReactTS_Frontend/public/azure-icons/NOTICE.md).';
const entries = index.map(({ id, name, categories }) => `  { id: ${JSON.stringify(id)}, name: ${JSON.stringify(name)}, categories: ${JSON.stringify(categories)} },`).join('\n');
writeFileSync(
  new URL('../src/features/sad/diagrams/azure-icons.ts', import.meta.url),
  `${header}\nexport interface AzureIcon {\n  id: string\n  name: string\n  categories: string[]\n}\n\nexport const AZURE_ICONS: AzureIcon[] = [\n${entries}\n]\n`,
);
writeFileSync(
  new URL('../../NestJS_Backend/src/modules/sad/domain/azure-icons.ts', import.meta.url),
  `${header}\n/** The Azure icons a box may show, by id, with their product names (the web app serves them; SAD PDFs draw the API's copy). */\nexport const AZURE_ICON_NAMES: ReadonlyMap<string, string> = new Map([\n${index.map(({ id, name }) => `  [${JSON.stringify(id)}, ${JSON.stringify(name)}],`).join('\n')}\n]);\nexport const AZURE_ICON_IDS: ReadonlySet<string> = new Set(AZURE_ICON_NAMES.keys());\n`,
);
console.log(`Wrote ${index.length} icons to public/azure-icons and the API, their index, and the API's icon ids and names`);
